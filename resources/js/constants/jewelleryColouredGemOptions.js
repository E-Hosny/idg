const SEP = '::'

/**
 * @param {number | ''} index
 * @param {string[]} list
 * @returns {string}
 */
export function encodeListSelection (index, list) {
  if (index === '' || index == null || Number.isNaN(Number(index))) {
    return ''
  }
  const i = Number(index)
  if (i < 0 || i >= list.length) {
    return ''
  }
  return `${i}${SEP}${list[i]}`
}

/**
 * @param {string} stored
 * @param {string[]} list
 * @returns { number | '' }
 */
export function decodeListSelectionToIndex (stored, list) {
  if (stored == null || stored === '') {
    return ''
  }
  if (typeof stored === 'string' && stored.includes(SEP)) {
    const idx = parseInt(stored.split(SEP)[0], 10)
    if (Number.isFinite(idx) && idx >= 0 && idx < list.length) {
      return idx
    }
  }
  const fromLabel = list.indexOf(stored)
  if (fromLabel >= 0) {
    return fromLabel
  }
  return ''
}

/**
 * @param {string} stored
 * @param {string[]} list
 * @returns {string} label only, for read-only display
 */
export function labelFromListSelection (stored, list) {
  if (stored == null || stored === '') {
    return ''
  }
  if (typeof stored === 'string' && stored.includes(SEP)) {
    const rest = stored.split(SEP)
    if (rest.length > 1) {
      return rest.slice(1).join(SEP)
    }
  }
  if (list.includes(stored)) {
    return stored
  }
  return stored
}
